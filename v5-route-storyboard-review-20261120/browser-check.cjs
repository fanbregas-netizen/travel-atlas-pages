const {chromium}=require('playwright');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
 fs.mkdirSync('route-storyboard-evidence',{recursive:true});
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 try{
 for(const width of [375,390,430]){
  const page=await browser.newPage({viewport:{width,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8765/v5-route-storyboard-review-20261120/',{waitUntil:'domcontentloaded',timeout:60000});
  await page.waitForSelector('#reviewBar .stage');
  assert.match(await page.title(),/路线流程逐步交互验收/);
  assert.match(await page.locator('#stepLabel').innerText(),/地图首页/);
  assert.equal(await page.locator('#stars button.star').count(),3);
  await page.locator('#dock [data-action="routes"]').click();
  assert.match(await page.locator('#sheetTitle').innerText(),/我的路线/);
  assert.equal(await page.locator('.routeRow').count(),2);
  await page.screenshot({path:'route-storyboard-evidence/'+width+'-01-route-list.png'});
  await page.locator('.routeRow').first().click();
  assert.match(await page.locator('#sheetTitle').innerText(),/查看行程/);
  await page.waitForFunction(()=>document.querySelectorAll('.star .number').length===3);
  await page.screenshot({path:'route-storyboard-evidence/'+width+'-02-saved-route.png'});
  await page.locator('#stars .star').first().evaluate(el=>el.click());
  assert.equal(await page.locator('#placeCard').isVisible(),true);
  await page.locator('#placeCard [data-action="close-place"]').last().click();
  assert.equal(await page.locator('#placeCard').isVisible(),false);
  await page.locator('#reviewBar [data-action="next-review"]').click();
  assert.match(await page.locator('#stepLabel').innerText(),/选择地点/);
  await page.locator('[data-action="add-direct"][data-id="s"]').click();
  await page.locator('[data-action="add-direct"][data-id="f"]').click();
  await page.locator('#sheetFoot [data-action="focus"]').click();
  assert.equal(await page.locator('#mini').isVisible(),true);
  assert.equal(await page.locator('#roadLayer').isVisible(),false);
  await page.locator('#stars .star').nth(1).evaluate(el=>el.click());
  await page.waitForFunction(()=>!document.querySelector('#popover').hidden);
  assert.match(await page.locator('#popover').innerText(),/移出本次路线/);
  await page.locator('#popover [data-action="remove-selected"]').click();
  assert.match(await page.locator('#miniCount').innerText(),/已选 1 处/);
  await page.locator('#stars .star').nth(1).evaluate(el=>el.click());
  assert.match(await page.locator('#miniCount').innerText(),/已选 2 处/);
  await page.locator('#mini [data-action="confirm-stars"]').click();
  assert.match(await page.locator('#sheetTitle').innerText(),/行程设置/);
  assert.equal(await page.locator('#roadLayer path[stroke-dasharray]').count()>0,true);
  await page.locator('#routeTitle').fill('路线交互测试');
  await page.locator('#sheetFoot [data-action="order"]').click();
  assert.match(await page.locator('#sheetTitle').innerText(),/排列顺序/);
  assert.equal(await page.locator('#roadLayer path[stroke-dasharray]').count(),0);
  assert.equal(await page.locator('#roadLayer path.hit').count()>0,true);
  await page.screenshot({path:'route-storyboard-evidence/'+width+'-03-order-road.png'});
  await page.locator('[data-action="move-down"][data-i="0"]').click();
  await page.locator('#roadLayer path.hit').first().evaluate(el=>el.dispatchEvent(new MouseEvent('click',{bubbles:true})));
  await page.waitForFunction(()=>!document.querySelector('#popover').hidden);
  await page.locator('#popover [data-action="expand-segment"]').click();
  assert.match(await page.locator('#popover').innerText(),/更改出行方式/);
  await page.screenshot({path:'route-storyboard-evidence/'+width+'-04-segment-detail.png'});
  await page.locator('#sheetFoot [data-action="save"]').click();
  assert.match(await page.locator('#sheetTitle').innerText(),/查看行程/);
  await page.locator('#sheetFoot [data-action="back-routes"]').click();
  assert.match(await page.locator('#sheetTitle').innerText(),/我的路线/);
  assert.equal(await page.locator('#stars .number').count()>=2,true);
  await page.locator('#sheetFoot [data-action="exit"]').click();
  assert.equal(await page.locator('#stars .number').count(),0);
  assert.equal(await page.locator('#roadLayer').isVisible(),false);
  await page.locator('#reviewBar [data-action="open-review"]').click();
  await page.locator('#reviewModal [data-action="approve"]').click();
  assert.match(await page.locator('#stepLabel').innerText(),/地图首页/);
  assert.equal(errors.length,0,'Browser JS errors: '+errors.join('; '));
  console.log('PASS '+width+'px: stages, route list, star removal, setting schematic, road order, bubble, save/back/exit, review');
  await page.close();
 }
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});