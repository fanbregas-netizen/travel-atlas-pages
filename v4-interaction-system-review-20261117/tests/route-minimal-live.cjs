'use strict';
const assert=require('node:assert/strict');
const cp=require('node:child_process'),fs=require('node:fs');
const {chromium}=require('playwright-core');
const base=process.env.INTERACTION_REVIEW_BASE_URL||'http://127.0.0.1:8765/v4-interaction-system-review-20261117/';
const chrome=['google-chrome','google-chrome-stable','chromium'].map(n=>{try{return cp.execFileSync('which',[n],{encoding:'utf8'}).trim()}catch{return null}}).find(Boolean);
if(!chrome)throw Error('Chromium unavailable');
fs.mkdirSync('route-minimal-qa',{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:chrome,args:['--no-sandbox','--disable-dev-shm-usage']});
 try{
  for(const width of [375,390]){
   const ctx=await browser.newContext({viewport:{width,height:844},hasTouch:true,isMobile:true,deviceScaleFactor:2,serviceWorkers:'block'});
   const page=await ctx.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
   page.setDefaultTimeout(30000);
   await page.goto(base+'route-minimal-review-20261117.html?qa='+width,{waitUntil:'domcontentloaded',timeout:60000});
   await page.waitForFunction(()=>!!window.__fpRouteLogicUI&&window.__atlasRV?.places?.length===6,null,{timeout:50000});
   await page.waitForTimeout(2200);
   let state=await page.evaluate(()=>window.__fpRouteLogicUI.getState());
   assert.equal(state.order.length,6);
   assert.equal(await page.locator('#stopsDock #fpRouteTools').count(),1);
   const layout=await page.evaluate(()=>{
     const viewport=innerWidth;
     const dock=document.getElementById('stopsDock').getBoundingClientRect();
     const tools=document.getElementById('fpRouteTools').getBoundingClientRect();
     const summary=document.getElementById('fpRouteSummary').getBoundingClientRect();
     const line=document.querySelector('#routeSegs .seg-stroke');
     return {viewport,dock:{x:dock.x,width:dock.width,right:dock.right},tools:{x:tools.x,right:tools.right},summary:{x:summary.x,width:summary.width},pathLength:line?.getAttribute('d')?.length||0};
   });
   assert.ok(layout.dock.x>=5&&layout.dock.x<=14&&layout.dock.right<=layout.viewport-5&&layout.dock.right>=layout.viewport-14&&layout.dock.width>=layout.viewport-25,'Dock is clipped/offscreen: '+JSON.stringify(layout));
   assert.ok(layout.summary.x>=0&&layout.summary.width>=25,'Route summary hidden: '+JSON.stringify(layout));
   assert.ok(layout.pathLength>10,'Main route guide must render immediately on map: '+JSON.stringify(layout));
   assert.equal(await page.locator('#fpRouteTools button:visible').count(),3,'compact Dock = summary, add, adjust');
   assert.equal(await page.locator('#stopsDock .rv-railrow:visible').count(),0,'duplicate location chips hidden');
   assert.equal(await page.locator('#fpRouteBadge:visible').count(),0,'demo badge hidden');
   assert.equal(await page.locator('#fpRoutePanelTabs:visible').count(),0,'four-way tabs removed');
   await page.screenshot({path:'route-minimal-qa/map-'+width+'.png'});
   await page.locator('#fpRouteTools .fp-slim-edit').click();
   await page.waitForFunction(()=>document.body.classList.contains('fp-route-panel-open'));
   await page.waitForTimeout(650);
   assert.equal(await page.locator('.fp-r-stop').count(),6);
   assert.equal(await page.locator('.fp-simple-optimize').count(),1);
   assert.equal(await page.locator('#fpRoutePanel [data-actions]').count(),6);
   assert.equal(await page.locator('#fpRoutePanel [data-move]').count(),0,'secondary actions hidden until asked');
   await page.screenshot({path:'route-minimal-qa/adjust-'+width+'.png'});
   await page.locator('[data-action="recommend"]').click();
   assert.equal(await page.locator('.fp-simple-proposal').count(),1);
   await page.locator('[data-action="apply"]').click();
   assert.equal(await page.locator('[data-action="undo"]').count(),1);
   await page.locator('[data-action="undo"]').click();
   await page.locator('[data-actions]').first().click();
   assert.equal(await page.locator('#fpRoutePanel [data-move]').count(),2);
   await page.locator('[data-actions]').first().click();
   assert.equal(await page.locator('#fpRoutePanel [data-move]').count(),0);
   await page.locator('[data-tab="setup"]').first().click();
   await page.waitForFunction(()=>document.getElementById('fpRoutePanelTitle').textContent==='行程设置');
   assert.equal(await page.locator('.fp-r-mode').count(),4);
   assert.equal(await page.locator('[data-leg]').count(),5);
   await page.locator('[data-mode="walk"]').click();
   state=await page.evaluate(()=>window.__fpRouteLogicUI.getState());
   assert.equal(state.mode,'walk');
   await page.waitForTimeout(1500);
   await page.screenshot({path:'route-minimal-qa/settings-'+width+'.png'});
   await page.locator('[data-action="close"]').click();
   assert.equal(await page.locator('body.fp-route-panel-open').count(),0);
   await page.evaluate(()=>document.querySelector('.route-pin')?.click());
   await page.waitForFunction(()=>document.body.classList.contains('fp-route-place-open'));
   assert.ok((await page.locator('#fpRouteCardTitle').innerText()).length>2);
   assert.equal(await page.locator('#fpRouteCard .fp-r-card-footer:visible').count(),0);
   await page.waitForTimeout(600);
   await page.screenshot({path:'route-minimal-qa/card-'+width+'.png'});
   await page.locator('[data-card-more]').click();
   assert.equal(await page.locator('#fpRouteCard .fp-r-card-footer:visible').count(),1);
   await page.locator('[data-card-close]').click();
   assert.equal(await page.locator('body.fp-route-place-open').count(),0);
   await page.locator('#fpRouteTools .fp-slim-add').click();
   assert.equal(await page.locator('.fp-r-listing').count(),7);
   assert.equal(await page.locator('[data-pick="rd_7_jiangxin"]').count(),1);
   await page.locator('[data-pick="rd_7_jiangxin"]').click();
   assert.equal((await page.evaluate(()=>window.__fpRouteLogicUI.getState())).order.length,7);
   await page.screenshot({path:'route-minimal-qa/picker-'+width+'.png'});
   assert.ok(errors.length===0,'page errors: '+errors.join('; '));
   console.log('PASS minimal route '+width+'px; single Dock / recommend + undo / progressive actions / setup / location card / point picker');
   await ctx.close();
  }
 }finally{await browser.close()}
})().catch(e=>{console.error('FAIL route minimal QA:',e.stack||e);process.exitCode=1});
